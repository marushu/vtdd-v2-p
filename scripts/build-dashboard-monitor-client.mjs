import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mountMonitorHome } from '../src/worker/dashboard-monitor-home.js';
import { computeMonitorView } from '../src/core/dashboard-monitor-state.js';

// Run only from canonical unbundled Node sources, never from the deployed Worker.
export function dashboardMonitorClientSource() {
  return `(${mountMonitorHome.toString()})(${computeMonitorView.toString()});`.replace(/<\/script/gi, '<\\/script');
}
export async function buildDashboardMonitorClient() {
  const target = fileURLToPath(new URL('../src/worker/dashboard-monitor-client.generated.js', import.meta.url));
  const source = dashboardMonitorClientSource();
  const output = '// @generated by scripts/build-dashboard-monitor-client.mjs. Do not edit directly.\n' +
    `export const dashboardMonitorClientScript = ${JSON.stringify(source)};\n`;
  await fs.writeFile(target, output);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildDashboardMonitorClient();
}
