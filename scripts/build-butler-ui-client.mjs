import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
export async function buildButlerUiClient() {
  const result = await build({ entryPoints: ['src/core/butler-ui-client.js'], bundle: true, write: false, format: 'iife', platform: 'browser', target: 'es2022', legalComments: 'none' });
  const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  await writeFile('src/core/butler-ui-client.generated.js', '// @generated by scripts/build-butler-ui-client.mjs\nexport const butlerUiClientScript = ' + JSON.stringify(script) + ';\n');
}
